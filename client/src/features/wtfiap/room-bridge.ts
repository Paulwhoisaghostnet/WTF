export interface WtfIapRoomMessage {
  type: "wtfiap:room";
  roomCode: string | null;
  roomType: "duel" | "party" | "tournament" | null;
}

export function wtfIapFundingRecoveryRoom(path: string): string | null {
  const url = new URL(path, "https://wtfiap.invalid");
  const room = url.searchParams.get("room");
  return url.pathname === "/wtfiap" && url.searchParams.get("funding") === "1" && room && /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(room) ? room.toLowerCase() : null;
}

export function readWtfIapRoomMessage(
  event: Pick<MessageEvent, "data" | "origin" | "source">,
  expectedWindow: Window | null,
  expectedOrigin: string,
): WtfIapRoomMessage | null {
  if (!expectedWindow || event.source !== expectedWindow || event.origin !== expectedOrigin) return null;
  const data: unknown = event.data;
  if (!data || typeof data !== "object" || Array.isArray(data)) return null;
  const message = data as Record<string, unknown>;
  if (message.type !== "wtfiap:room") return null;
  if (message.roomCode === null && message.roomType === null) return { type: "wtfiap:room", roomCode: null, roomType: null };
  // Hosted room identity is the UUID generated by the authority, not a URL or wallet request.
  if (typeof message.roomCode !== "string" || !/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(message.roomCode)) return null;
  if (message.roomType !== "duel" && message.roomType !== "party" && message.roomType !== "tournament") return null;
  return { type: "wtfiap:room", roomCode: message.roomCode, roomType: message.roomType };
}
