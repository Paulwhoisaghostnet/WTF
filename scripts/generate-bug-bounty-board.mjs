import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, "docs/reference/bug-bounty-records.json");
const OUTPUT = path.join(ROOT, ".agents/docs/live/BUG_BOUNTY_BOARD.md");
const SUPPORTED_STATUSES = new Set([
  "Open",
  "Claimed",
  "In Progress",
  "Blocked",
  "Fixed",
  "Verified",
  "Archived",
]);
const PRIORITY_BONUS = new Map([
  ["P0", 5],
  ["P1", 4],
  ["P2", 3],
  ["P3", 2],
  ["P4", 1],
]);
const STATUS_ORDER = new Map([...SUPPORTED_STATUSES].map((status, index) => [status, index]));

function compareRecords(left, right) {
  return STATUS_ORDER.get(left.status) - STATUS_ORDER.get(right.status)
    || Number(left.priority.slice(1)) - Number(right.priority.slice(1))
    || right.points - left.points
    || Number(right.id.slice("WTF-BB-".length)) - Number(left.id.slice("WTF-BB-".length));
}

function escapeCell(value) {
  return String(value).replaceAll("\\", "\\\\").replaceAll("|", "\\|").replaceAll(/\r?\n/gu, " ");
}

function splitTableRow(line) {
  const cells = [];
  let cell = "";
  let escaped = false;
  for (const character of line.slice(1, -1)) {
    if (escaped) {
      cell += character;
      escaped = false;
    } else if (character === "\\") {
      escaped = true;
    } else if (character === "|") {
      cells.push(cell.trim());
      cell = "";
    } else {
      cell += character;
    }
  }
  cells.push(cell.trim());
  return cells;
}

function requiredString(record, field) {
  const value = record[field];
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error(`${record.id ?? "bounty record"} is missing ${field}`);
  }
  return value.trim();
}

function requiredInteger(record, field, minimum = 0) {
  const value = record[field];
  if (!Number.isInteger(value) || value < minimum) {
    throw new Error(`${record.id ?? "bounty record"} has invalid ${field}`);
  }
  return value;
}

export function validateBountyRecords(records) {
  if (!Array.isArray(records)) throw new Error("canonical bounty records must be an array");
  const seen = new Set();
  for (const record of records) {
    const id = requiredString(record, "id");
    if (!/^WTF-BB-\d{3,}$/u.test(id)) throw new Error(`invalid bounty ID ${id}`);
    if (seen.has(id)) throw new Error(`duplicate bounty ID ${id}`);
    seen.add(id);

    const status = requiredString(record, "status");
    if (!SUPPORTED_STATUSES.has(status)) throw new Error(`unsupported status ${status} for ${id}`);
    requiredString(record, "owner");
    const lastTouched = requiredString(record, "lastTouched");
    if (lastTouched !== "-" && !/^\d{4}-\d{2}-\d{2}$/u.test(lastTouched)) {
      throw new Error(`${id} has invalid lastTouched ${lastTouched}`);
    }
    requiredString(record, "category");
    const priority = requiredString(record, "priority");
    if (!PRIORITY_BONUS.has(priority)) throw new Error(`${id} has invalid priority ${priority}`);
    requiredString(record, "title");
    if (typeof record.body !== "string") throw new Error(`${id} is missing body`);

    const complexity = requiredInteger(record, "complexity", 1);
    const functionalityDanger = requiredInteger(record, "functionalityDanger");
    const securityDanger = requiredInteger(record, "securityDanger");
    const points = requiredInteger(record, "points", 1);
    requiredInteger(record, "rank", 1);
    const expectedPoints = complexity + functionalityDanger + securityDanger + PRIORITY_BONUS.get(priority);
    if (points !== expectedPoints) {
      throw new Error(`${id} points ${points} do not match score ${expectedPoints}`);
    }
  }
  for (const record of records) {
    const expectedRank = 1 + records.filter((candidate) => candidate.points > record.points).length;
    if (record.rank !== expectedRank) {
      throw new Error(`${record.id} rank ${record.rank} does not match derived rank ${expectedRank}`);
    }
  }
  return records;
}

function statusCounts(records) {
  const counts = Object.fromEntries([...SUPPORTED_STATUSES].map((status) => [status, 0]));
  for (const record of records) counts[record.status] += 1;
  return counts;
}

export function renderBountyBoard(records) {
  validateBountyRecords(records);
  const orderedRecords = [...records].sort(compareRecords);
  const counts = statusCounts(records);
  const lines = [
    "# WTF Bug Bounty Board",
    "",
    "> Generated by `npm run bounty:board` from `docs/reference/bug-bounty-records.json`. Do not edit this Markdown by hand.",
    "> Historical pre-canonical evidence is preserved in `docs/reference/BUG_BOUNTY_BOARD_LEGACY_2026-08-30.md`.",
    "",
    "## Workflow",
    "",
    "1. Select the highest-priority actionable record that matches the task scope.",
    "2. Claim it by editing its canonical JSON record, then regenerate this board.",
    "3. Investigate root cause before changing implementation.",
    "4. Record correction and reproducible verification evidence before closing it.",
    "5. Run `npm run bounty:board:check` before committing.",
    "",
    "## Status Values",
    "",
    "- `Open`: confirmed and unowned.",
    "- `Claimed`: actively investigated.",
    "- `In Progress`: correction is being implemented.",
    "- `Blocked`: requires a named external decision, credential, production action, or dependency.",
    "- `Fixed`: correction exists but target-environment verification remains.",
    "- `Verified`: correction has convincing reproducible verification.",
    "- `Archived`: historical and no longer actionable.",
    "",
    "## Canonical Counts",
    "",
    `Total: **${records.length}** · Open: **${counts.Open}** · Claimed: **${counts.Claimed}** · In Progress: **${counts["In Progress"]}** · Blocked: **${counts.Blocked}** · Fixed: **${counts.Fixed}** · Verified: **${counts.Verified}** · Archived: **${counts.Archived}**`,
    "",
    "## Canonical Board",
    "",
    "| ID | Status | Owner/Session | Last touched | Category | Priority | Points | Rank | C | F | S | Title |",
    "| --- | --- | --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: | --- |",
  ];

  for (const record of orderedRecords) {
    lines.push(`| ${record.id} | ${escapeCell(record.status)} | ${escapeCell(record.owner)} | ${escapeCell(record.lastTouched)} | ${escapeCell(record.category)} | ${record.priority} | ${record.points} | ${record.rank} | ${record.complexity} | ${record.functionalityDanger} | ${record.securityDanger} | ${escapeCell(record.title)} |`);
  }

  lines.push("", "## Issue Details", "");
  for (const record of orderedRecords) {
    lines.push(
      `### ${record.id} - ${record.title}`,
      "",
      `- Category: ${record.category}`,
      `- Priority: ${record.priority}`,
      `- Status: ${record.status}`,
      `- Owner/Session: ${record.owner}`,
      `- Last touched: ${record.lastTouched}`,
      `- Score: C${record.complexity} + F${record.functionalityDanger} + S${record.securityDanger} + ${record.priority}(${PRIORITY_BONUS.get(record.priority)}) = ${record.points}`,
    );
    const body = record.body.trim();
    if (body) lines.push(body);
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

function detailField(body, name) {
  return body.match(new RegExp(`^- ${name}:\\s*(.+)$`, "mu"))?.[1]?.trim() ?? null;
}

export function parseGeneratedBountyBoard(markdown) {
  const summaryStart = markdown.indexOf("## Canonical Board");
  const detailsStart = markdown.indexOf("## Issue Details");
  if (summaryStart < 0 || detailsStart < 0 || detailsStart <= summaryStart) {
    throw new Error("generated bounty board is missing canonical sections");
  }

  const summary = [];
  const summaryById = new Map();
  for (const line of markdown.slice(summaryStart, detailsStart).split(/\r?\n/u)) {
    if (!line.startsWith("| WTF-BB-")) continue;
    const cells = splitTableRow(line);
    if (cells.length !== 12) throw new Error(`invalid summary row: ${line}`);
    const [id, status, owner, lastTouched, category, priority, points, rank, complexity, functionalityDanger, securityDanger, title] = cells;
    if (summaryById.has(id)) throw new Error(`duplicate summary record ${id}`);
    const record = { id, status, owner, lastTouched, category, priority, points, rank, complexity, functionalityDanger, securityDanger, title };
    summary.push(record);
    summaryById.set(id, record);
  }

  const details = [];
  const detailsById = new Map();
  const detailText = markdown.slice(detailsStart);
  const matches = [...detailText.matchAll(/^### (WTF-BB-\d+) - (.+)$/gmu)];
  for (let index = 0; index < matches.length; index += 1) {
    const [, id, title] = matches[index];
    if (detailsById.has(id)) throw new Error(`duplicate detail record ${id}`);
    const start = matches[index].index + matches[index][0].length;
    const end = matches[index + 1]?.index ?? detailText.length;
    const body = detailText.slice(start, end);
    const score = detailField(body, "Score")?.match(/^C(\d+) \+ F(\d+) \+ S(\d+) \+ (P\d)\(\d+\) = (\d+)$/u);
    if (!score) throw new Error(`invalid score detail for ${id}`);
    const record = {
      id,
      title: title.trim(),
      category: detailField(body, "Category"),
      priority: detailField(body, "Priority"),
      status: detailField(body, "Status"),
      owner: detailField(body, "Owner/Session"),
      lastTouched: detailField(body, "Last touched"),
      complexity: score[1],
      functionalityDanger: score[2],
      securityDanger: score[3],
      points: score[5],
    };
    details.push(record);
    detailsById.set(id, record);
  }

  for (const summaryRecord of summary) {
    const detail = detailsById.get(summaryRecord.id);
    if (!detail) throw new Error(`missing detail record for ${summaryRecord.id}`);
    for (const field of ["status", "owner", "lastTouched", "category", "priority", "points", "complexity", "functionalityDanger", "securityDanger", "title"]) {
      if (summaryRecord[field] !== detail[field]) {
        throw new Error(`${field} disagreement for ${summaryRecord.id}: summary=${summaryRecord[field]} detail=${detail[field]}`);
      }
    }
  }
  for (const detail of details) {
    if (!summaryById.has(detail.id)) throw new Error(`missing summary record for ${detail.id}`);
  }
  return { summary, details };
}

async function main() {
  const source = JSON.parse(await readFile(SOURCE, "utf8"));
  const generated = renderBountyBoard(source.records);
  parseGeneratedBountyBoard(generated);
  if (process.argv.includes("--check")) {
    const current = await readFile(OUTPUT, "utf8").catch(() => "");
    if (current !== generated) {
      console.error("Bug bounty board is stale. Run: npm run bounty:board");
      process.exit(1);
    }
    console.log(`Bug bounty board is current with ${source.records.length} canonical records.`);
    return;
  }
  await writeFile(OUTPUT, generated, "utf8");
  console.log(`Wrote ${path.relative(ROOT, OUTPUT)} with ${source.records.length} canonical records.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
