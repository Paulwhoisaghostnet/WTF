#!/usr/bin/env node

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const walletConnectProjectId = process.env.VITE_WALLETCONNECT_PROJECT_ID?.trim() || "";

const tezosVendor = path.join(root, "public/creation-tools/macaroni/vendor/tezos.js");
const octezVendor = path.join(root, "public/creation-tools/macaroni/vendor/octez-connect.js");
const tezosVendorCopies = [
  "gnocchi",
  "lasagna",
  "penne",
  "ravioli",
  "rotini",
  "spaghetti",
].map((tool) => path.join(root, "public/creation-tools", tool, "vendor/tezos.js"));
const octezVendorCopies = [
  "gnocchi",
  "lasagna",
  "penne",
  "ravioli",
  "rotini",
  "spaghetti",
].map((tool) => path.join(root, "public/creation-tools", tool, "vendor/octez-connect.js"));

const banner = {
  js: "/* Generated by scripts/build-tezos-browser-vendors.mjs. Do not edit by hand. */",
};

const nodeFallbackPlugin = {
  name: "node-fallbacks-for-browser-vendors",
  setup(pluginBuild) {
    pluginBuild.onResolve(
      { filter: /^(node:)?(fs|net|tls|http|https|os|stream|zlib)$/ },
      (args) => ({ path: args.path.replace(/^node:/, ""), namespace: "empty-node" })
    );
    pluginBuild.onLoad({ filter: /.*/, namespace: "empty-node" }, () => ({
      loader: "js",
      contents: [
        "export default {};",
        "export class Agent {}",
        "export class Readable {}",
        "export function request() { throw new Error('Node request API is unavailable in browser wallet bundles.'); }",
        "export function get() { throw new Error('Node request API is unavailable in browser wallet bundles.'); }",
        "export function createGzip() { throw new Error('Node zlib API is unavailable in browser wallet bundles.'); }",
        "export function createGunzip() { throw new Error('Node zlib API is unavailable in browser wallet bundles.'); }",
      ].join("\n"),
    }));
  },
};

async function buildBrowserBundle({ contents, outfile }) {
  mkdirSync(path.dirname(outfile), { recursive: true });
  await build({
    stdin: {
      contents,
      loader: "js",
      resolveDir: root,
      sourcefile: path.basename(outfile),
    },
    outfile,
    bundle: true,
    format: "iife",
    platform: "browser",
    target: ["es2020"],
    mainFields: ["browser", "module", "main"],
    minify: true,
    banner,
    define: {
      global: "globalThis",
      "process.env.NODE_ENV": '"production"',
      "process.env": "{}",
    },
    plugins: [nodeFallbackPlugin],
    logLevel: "info",
  });

  // esbuild preserves whitespace-only lines inside bundled license comments.
  // Normalize generated output so the checked-in artifacts pass diff hygiene.
  const output = readFileSync(outfile, "utf8");
  writeFileSync(outfile, output.replace(/[ \t]+$/gm, ""));
}

await buildBrowserBundle({
  outfile: tezosVendor,
  contents: `
    import { Buffer } from "buffer";
    import { BeaconWallet } from "@taquito/beacon-wallet";
    import { TezosToolkit, MichelsonMap, OpKind, MichelCodecPacker } from "@taquito/taquito";
    import { bytesToString, stringToBytes, validateAddress, ValidationResult } from "@taquito/utils";
    import { blake2b } from "blakejs";

    globalThis.Buffer ||= Buffer;
    globalThis.process ||= { env: {}, versions: {} };
    globalThis.TZ = {
      TezosToolkit,
      MichelsonMap,
      MichelCodecPacker,
      OpKind,
      BeaconWallet,
      stringToBytes,
      bytesToString,
      validateAddress,
      ValidationResult,
      blake2b,
    };
  `,
});

for (const target of tezosVendorCopies) {
  mkdirSync(path.dirname(target), { recursive: true });
  copyFileSync(tezosVendor, target);
}

await buildBrowserBundle({
  outfile: octezVendor,
  contents: `
    import {
      BeaconEvent,
      DAppClient,
      NetworkType,
      PermissionScope,
      getDAppClientInstance,
    } from "@tezos-x/octez.connect-sdk";

    globalThis.MacaroniOctezConnect = {
      BeaconEvent,
      DAppClient,
      NetworkType,
      PermissionScope,
      getDAppClientInstance,
      walletConnectProjectId: ${JSON.stringify(walletConnectProjectId)},
    };
  `,
});

for (const target of octezVendorCopies) {
  mkdirSync(path.dirname(target), { recursive: true });
  copyFileSync(octezVendor, target);
}

console.log("Built Taquito and Octez Connect browser vendor bundles.");
